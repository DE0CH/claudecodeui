/**
 * SQLite's date functions as used by the repositories' SQL, so its time comparisons and orderings keep SQLite's
 * meaning: `julianday(text)` (fractional days) and `datetime(text)` (`YYYY-MM-DD HH:MM:SS`, UTC). Both accept
 * SQLite's text form and ISO-8601 with a `T`/`Z`/offset, and return NULL for NULL, empty or unparsable text, as
 * SQLite does. Replaced on every start (under the init lock), so a change here needs no schema version.
 */
export const SQLITE_COMPAT_FUNCTIONS_SQL = `
CREATE OR REPLACE FUNCTION sqlite_ts(t text) RETURNS timestamp LANGUAGE plpgsql STABLE AS $fn$
BEGIN
  IF t IS NULL OR btrim(t) = '' THEN RETURN NULL; END IF;
  IF t ~* '(z|[+-][0-9][0-9](:?[0-9][0-9])?)\\s*$' AND t ~ '[0-9]:[0-9]' THEN
    RETURN (t::timestamptz AT TIME ZONE 'UTC');
  END IF;
  RETURN t::timestamp;
EXCEPTION WHEN others THEN
  RETURN NULL;
END
$fn$;
CREATE OR REPLACE FUNCTION julianday(t text) RETURNS double precision LANGUAGE sql STABLE AS $fn$
  SELECT extract(epoch FROM sqlite_ts(t))::double precision / 86400.0 + 2440587.5
$fn$;
CREATE OR REPLACE FUNCTION datetime(t text) RETURNS text LANGUAGE sql STABLE AS $fn$
  SELECT to_char(sqlite_ts(t), 'YYYY-MM-DD HH24:MI:SS')
$fn$;
`;

