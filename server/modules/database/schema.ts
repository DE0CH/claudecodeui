/**
 * The database schema, in Postgres (Jarvis 3 fork). It mirrors upstream's SQLite schema after all of upstream's
 * migrations (upstream: schema.ts + migrations.ts), column for column, with the same value shapes: timestamps are
 * text in SQLite's `YYYY-MM-DD HH:MM:SS` form (UTC; `NOW_TEXT`), text columns use the "C" collation (bytewise, like
 * SQLite's BINARY: orderings match upstream whatever the database's locale), booleans are 0/1 integers, ids are integer
 * identities. `isStarred`/`isArchived` keep their case (quoted). A fresh schema has no legacy shapes to repair, so
 * there are no migrations: a change to a table is a new statement appended to `SCHEMA_VERSIONS`.
 */
